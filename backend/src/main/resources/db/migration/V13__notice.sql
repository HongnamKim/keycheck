-- 디스코드 판매 공지 한 건. 판매처 공지 서버의 메시지 하나가 한 줄이다.
CREATE TABLE notice (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 원래 서버 메시지 id (디스코드 snowflake). 같은 메시지를 두 번 저장하지 않게 한다.
    source_message_id  BIGINT       NOT NULL UNIQUE,
    -- 팔로우 채널에 복사된 메시지 id. 봇이 받은 공지만 있고, 과거 공지 가져오기는 NULL.
    channel_message_id BIGINT,
    -- 메시지가 올라온 채널 id
    channel_id         BIGINT       NOT NULL,
    -- 판매처 (KoreanVendor)
    vendor             VARCHAR(20)  NOT NULL,
    -- 어떻게 들어왔는지 (BOT: 봇이 받음, BACKFILL: 과거 공지 가져오기)
    origin             VARCHAR(20)  NOT NULL,
    -- 원래 메시지 작성 시각
    posted_at          TIMESTAMPTZ  NOT NULL,
    -- 메시지 본문
    content            TEXT         NOT NULL,
    -- 본문에 글이 있는지. 이미지만 올라온 딸린 메시지는 false.
    has_text           BOOLEAN      NOT NULL,
    -- 디스코드가 준 메시지 원문 JSON
    raw                JSONB        NOT NULL,
    -- 이 메시지가 딸린 글 공지. 글 공지 자신이거나 짝을 못 찾았으면 NULL.
    parent_id          BIGINT REFERENCES notice (id),
    -- 요약 상태 (SummaryStatus)
    summary_status     VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    -- 요약한 모델 이름
    summarized_by      VARCHAR(100),
    -- 요약을 마친 시각
    summarized_at      TIMESTAMPTZ,
    created_at         TIMESTAMPTZ  NOT NULL,
    updated_at         TIMESTAMPTZ  NOT NULL
);

CREATE INDEX idx_notice_summary_status_posted_at ON notice (summary_status, posted_at);
CREATE INDEX idx_notice_vendor_posted_at ON notice (vendor, posted_at DESC);

-- 공지에 붙은 이미지 첨부
CREATE TABLE notice_attachment (
    -- 디스코드 첨부 id
    id             BIGINT PRIMARY KEY,
    notice_id      BIGINT       NOT NULL REFERENCES notice (id) ON DELETE CASCADE,
    -- 공지 안의 순서(0부터)
    position       INTEGER      NOT NULL,
    filename       TEXT         NOT NULL,
    -- 디스코드 CDN 주소. 만료되면 새로 받아 갱신한다.
    source_url     TEXT,
    -- 저장소(R2) 보관 상태 (ArchiveStatus)
    archive_status VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    -- 보관에 실패한 횟수
    failures       INTEGER      NOT NULL DEFAULT 0
);

CREATE INDEX idx_notice_attachment_notice_id ON notice_attachment (notice_id);
CREATE INDEX idx_notice_attachment_pending ON notice_attachment (id) WHERE archive_status = 'PENDING';

-- 채널마다 어디까지 읽었는지
CREATE TABLE notice_channel_cursor (
    channel_id      BIGINT PRIMARY KEY,
    -- 마지막으로 읽은 메시지 id
    last_message_id BIGINT NOT NULL
);

-- 공지에서 뽑은 판매 건. 공지 하나에서 여러 건이 나올 수 있다.
CREATE TABLE sale_item (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notice_id    BIGINT       NOT NULL REFERENCES notice (id) ON DELETE CASCADE,
    -- 공지 안의 순서(0부터)
    position     INTEGER      NOT NULL,
    -- 공지에서 복사한 판매처와 공지 시각
    vendor       VARCHAR(20)  NOT NULL,
    posted_at    TIMESTAMPTZ  NOT NULL,
    product_name VARCHAR(200) NOT NULL,
    category     VARCHAR(20)  NOT NULL,
    sale_type    VARCHAR(20)  NOT NULL,
    phase        VARCHAR(20)  NOT NULL,
    -- 판매 시작·종료 (한국 시각). 모르면 NULL.
    start_date   DATE,
    start_time   TIME,
    end_date     DATE,
    end_time     TIME,
    -- 배송 안내
    shipping_note TEXT,
    -- 한국어 요약 줄 목록
    summary_lines JSONB       NOT NULL,
    -- 링크 목록 [{text, url}]
    links        JSONB        NOT NULL,
    -- 이 건에 쓸 첨부 id 목록. 첫째가 대표 이미지.
    image_ids    JSONB        NOT NULL,
    -- 화면에서 숨김
    hidden       BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at   TIMESTAMPTZ  NOT NULL
);

CREATE INDEX idx_sale_item_notice_id ON sale_item (notice_id);
CREATE INDEX idx_sale_item_hidden_posted_at ON sale_item (hidden, posted_at DESC, id DESC);
