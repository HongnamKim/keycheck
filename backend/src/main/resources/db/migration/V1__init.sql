CREATE TABLE post (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id                BIGINT       NOT NULL UNIQUE,
    title                   VARCHAR(500) NOT NULL,
    author                  VARCHAR(200) NOT NULL,
    category                VARCHAR(20)  NOT NULL,
    posted_at               TIMESTAMPTZ,
    views                   INTEGER      NOT NULL DEFAULT 0,
    replies                 INTEGER      NOT NULL DEFAULT 0,
    stats_checked_at        TIMESTAMPTZ  NOT NULL,
    original_url            VARCHAR(500) NOT NULL,
    body_text               TEXT         NOT NULL,
    summary_status          VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    summary_lines           JSONB,
    specs                   JSONB,
    representative_image_id BIGINT,
    hidden                  BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at              TIMESTAMPTZ  NOT NULL,
    updated_at              TIMESTAMPTZ  NOT NULL
);

CREATE INDEX idx_post_hidden_posted_at ON post (hidden, posted_at DESC);
CREATE INDEX idx_post_hidden_views ON post (hidden, views DESC);
CREATE INDEX idx_post_category ON post (category);

CREATE TABLE post_image (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id         BIGINT       NOT NULL REFERENCES post (id) ON DELETE CASCADE,
    url             TEXT         NOT NULL,
    source          VARCHAR(20)  NOT NULL,
    position        INTEGER      NOT NULL,
    excluded_reason VARCHAR(100)
);

CREATE INDEX idx_post_image_post_id ON post_image (post_id);

ALTER TABLE post
    ADD CONSTRAINT fk_post_representative_image
        FOREIGN KEY (representative_image_id) REFERENCES post_image (id) ON DELETE SET NULL;
