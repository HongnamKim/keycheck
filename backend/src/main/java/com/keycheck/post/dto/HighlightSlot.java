package com.keycheck.post.dto;

/**
 * 메인 하이라이트 칸. 이 순서로 고르고, 앞 칸에 들어간 글은 뒤 칸에서 건너뛴다. 창(최근 N일, 작성일 기준) 안에 후보가 없으면 30일(처음 창이 더
 * 짧을 때만) → 90일 → 전체로 넓힌다.
 */
public enum HighlightSlot {
  /** 큰 칸: 최근 7일 공동구매 중 조회수 1위 */
  FEATURE,
  /** 세로 칸: 최근 14일 IC 중 조회수 1위 */
  TALL,
  /**
   * 마감 띠: 오늘(한국 날짜)이나 그 뒤에 마감하는 공동구매 중 마감이 가장 가까운 글. 없으면 최근 14일 공동구매 중 조회수 1위를 사진 칸으로
   */
  DEADLINE,
  /** 작은 칸 1: 최근 14일 IC 중 댓글 1위 */
  IC_REPLIES,
  /** 작은 칸 2: 최근 14일 IC 중 조회수 1위(세로 칸 글을 건너뛰므로 흔히 2위) */
  IC_VIEWS,
  /** 작은 칸 3: 최근 30일 공동구매 중 조회수 1위 */
  GB_VIEWS
}
